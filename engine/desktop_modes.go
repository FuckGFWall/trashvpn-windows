// Only the generated header and routing rules are rebuilt. In particular, never
// re-render keys/endpoints from mutable global account or scan state on a reload.
func desktopModeConfig(previous []byte, s clientSettings, st clientState) ([]byte, error) {
	text := strings.ReplaceAll(string(previous), "\r\n", "\n")
	begin, end := strings.Index(text, "\nproxies:\n"), strings.Index(text, "\nrules:\n")
	if !strings.HasPrefix(text, "# generated by xehn ") || begin < 0 || end <= begin {
		return nil, fmt.Errorf("不是受支持的客户端配置，未修改运行中的内核")
	}
	if st.PsiphonMode || st.OpenVPNMode {
		return nil, fmt.Errorf("旧版出口连接不支持桌面模式热切换")
	}
	o := desktopConnectOptions(s)
	// Session ports and endpoint family cannot be changed by this operation.
	o.mixedPort, o.apiPort, o.allowLan = st.MixedPort, st.APIPort, st.AllowLan
	var b strings.Builder
	b.WriteString(renderClientHeader(o))
	if !o.tunMode {
		b.WriteString("tun:\n  enable: false\n")
	}
	b.WriteString(text[begin+1 : end+1])
	b.WriteString("rules:\n")
	for _, rule := range routeRules(o, "WARP") {
		fmt.Fprintf(&b, "  - %s\n", rule)
	}
	fmt.Fprintf(&b, "  - MATCH,%s\n", routingFallback(o, "WARP"))
	return []byte(b.String()), nil
}

type modeSwitchOps struct {
	reload       func(context.Context, []byte, bool) error
	setProxy     func() (*core.ProxySnapshot, error)
	restoreProxy func(*core.ProxySnapshot) error
	config       func([]byte) error
	state        func(clientState) error
}

// Commit only after reload + host capture succeeded; every failure rolls back
// the config, host proxy and recorded session. Original PAC/proxy snapshots are
// kept across routing-only reloads and are restored before entering TUN.
func applyDesktopModes(ctx context.Context, old clientState, before, after []byte, tun bool, ops modeSwitchOps) (err error) {
	next := old
	next.TUN = tun
	if old.TUN != tun {
		next.NoProxy = tun
	}
	proxyTouched, filesTouched := false, false
	var fresh *core.ProxySnapshot
	defer func() {
		if err == nil {
			return
		}
		rollback, cancel := context.WithTimeout(context.Background(), 20*time.Second)
		defer cancel()
		var failures []error
		failures = append(failures, ops.reload(rollback, before, old.TUN))
		if proxyTouched {
			if old.TUN {
				failures = append(failures, ops.restoreProxy(fresh))
			} else {
				_, e := ops.setProxy()
				failures = append(failures, e)
			}
		}
		if filesTouched {
			failures = append(failures, ops.config(before), ops.state(old))
		}
		if e := errors.Join(failures...); e != nil {
			err = errors.Join(err, fmt.Errorf("回滚未完成，请检查连接及系统代理：%w", e))
		}
	}()
	if err = ops.reload(ctx, after, tun); err != nil {
		return err
	}
	if old.TUN != tun {
		next.ProxyWarn = ""
		if tun {
			if len(old.ProxySnap) > 0 {
				var snap core.ProxySnapshot
				if err = json.Unmarshal(old.ProxySnap, &snap); err != nil {
					return err
				}
				proxyTouched = true
				if err = ops.restoreProxy(&snap); err != nil {
					return err
				}
			}
			next.ProxySnap = nil
		} else {
			fresh, err = ops.setProxy()
			proxyTouched = fresh != nil
			if err != nil {
				return err
			}
			next.ProxySnap, err = json.Marshal(fresh)
			if err != nil {
				return err
			}
		}
	}
	filesTouched = true
	if err = ops.config(after); err != nil {
		return err
	}
	err = ops.state(next)
	return err
}

func runDesktopModes(parent context.Context, _ options) error {
	ctx, cancel := desktopContext(parent)
	defer cancel()
	s := loadSettings()
	if err := json.Unmarshal([]byte(os.Getenv("WARP_DESKTOP_SETTINGS")), &s); err != nil {
		return err
	}
	if s.CaptureMode != captureProxy && s.CaptureMode != captureTun || s.ProxyMode != modeGlobal && s.ProxyMode != modeBypass {
		return fmt.Errorf("未知的接管或路由模式")
	}
	if s.CaptureMode == captureTun && !core.IsElevated() {
		return fmt.Errorf("TUN 需要管理员权限")
	}
	st, err := loadState()
	if err != nil {
		return err
	}
	dir, err := coreDir()
	if err != nil {
		return err
	}
	if !st.Connected || !core.ProcessMatches(st.CorePID, core.CoreInDir(dir)) {
		return fmt.Errorf("没有可热切换的本地连接")
	}
	if s.ProxyMode == modeBypass && !core.GeoDataReady(dir) {
		// Do not silently turn split routing into global routing.
		if err := core.DownloadGeoData(ctx, dir, func(line string) { fmt.Println(line) }); err != nil {
			return err
		}
	}
	before, err := os.ReadFile(filepath.Join(dir, core.ConfigName))
	if err != nil {
		return err
	}
	after, err := desktopModeConfig(before, s, st)
	if err != nil {
		return err
	}
	if err := core.TestConfig(core.CoreInDir(dir), dir, after); err != nil {
		return err
	}
	c, err := core.New(core.Config{BinaryPath: core.CoreInDir(dir), WorkDir: dir})
	if err != nil {
		return err
	}
	err = applyDesktopModes(ctx, st, before, after, s.CaptureMode == captureTun, modeSwitchOps{
		reload: func(ctx context.Context, config []byte, tun bool) error {
			return core.ReloadConfig(ctx, st.APIPort, config, tun)
		},
		setProxy:     func() (*core.ProxySnapshot, error) { return core.SetSystemProxy(st.MixedPort) },
		restoreProxy: core.UnsetSystemProxy, config: c.WriteConfig, state: saveState,
	})
	if err == nil {
		fmt.Println("接管 / 路由模式已热切换，保留当前节点与内核进程")
	}
	return err
}

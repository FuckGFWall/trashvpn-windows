func TestDesktopModeConfigPreservesNodeAndChain(t *testing.T) {
	home := t.TempDir()
	t.Setenv("WARP_CLIENT_HOME", home)
	dir := filepath.Join(home, "core")
	if err := os.MkdirAll(dir, 0700); err != nil {
		t.Fatal(err)
	}
	for _, name := range core.GeoDataNames() {
		if err := os.WriteFile(filepath.Join(dir, name), make([]byte, 512*1024), 0600); err != nil {
			t.Fatal(err)
		}
	}
	// Opaque node material must survive even without loading an account.
	nodes := "proxies:\n  - name: outer\n    type: socks5\n    server: 192.0.2.1\n    port: 1080\n  - name: inner\n    type: socks5\n    server: 192.0.2.2\n    port: 1080\n    dialer-proxy: outer\nproxy-groups:\n  - name: WARP\n    type: select\n    proxies: [inner]\n"
	before := []byte("# generated by xehn (xehn)\nmixed-port: 7891\n" + nodes + "rules:\n  - MATCH,WARP\n")
	s := defaultSettings()
	s.DNSCustom = "223.5.5.5,1.1.1.1"
	st := clientState{Connected: true, MixedPort: 17891, APIPort: 19090, CorePID: 123, Family: "v4"}
	for _, tun := range []bool{true, false} {
		for _, route := range []string{modeGlobal, modeBypass} {
			s.CaptureMode = captureProxy
			if tun {
				s.CaptureMode = captureTun
			}
			s.ProxyMode = route
			after, err := desktopModeConfig(before, s, st)
			if err != nil {
				t.Fatal(err)
			}
			text := string(after)
			if !strings.Contains(text, nodes) || !strings.Contains(text, "mixed-port: 17891") || !strings.Contains(text, "external-controller: 127.0.0.1:19090") {
				t.Fatal("node/chain/controller changed")
			}
			if strings.Contains(text, "enable: true\n  stack: gvisor") != tun {
				t.Fatal("TUN mode mismatch")
			}
			if !tun && !strings.Contains(text, "tun:\n  enable: false") {
				t.Fatal("TUN disable must be explicit")
			}
			if strings.Contains(text, "GEOSITE,cn,DIRECT") != (route == modeBypass) || strings.Contains(text, "nameserver-policy:") != (route == modeBypass) {
				t.Fatal("routing and split DNS must switch together")
			}
			before = after
		}
	}
	if _, err := desktopModeConfig([]byte("proxies:\n"), s, st); err == nil {
		t.Fatal("foreign config must not be rewritten")
	}
}

func TestDesktopModeTransaction(t *testing.T) {
	for _, test := range []struct {
		name           string
		oldTun, newTun bool
		fail           string
	}{
		{"route-only-proxy", false, false, ""}, {"route-only-tun", true, true, ""},
		{"proxy-to-tun", false, true, ""}, {"tun-to-proxy", true, false, ""},
		{"reload-failed", false, true, "reload"}, {"restore-failed", false, true, "restore"},
		{"set-failed", true, false, "set"}, {"config-write-failed", false, true, "config"},
		{"state-write-failed", true, false, "state"},
	} {
		t.Run(test.name, func(t *testing.T) {
			baseline := &core.ProxySnapshot{}
			snap, _ := json.Marshal(baseline)
			old := clientState{Connected: true, CorePID: 123, MixedPort: 7891, APIPort: 9090, TUN: test.oldTun, NoProxy: test.oldTun, ProxySnap: snap, StartedAt: "original-session"}
			stored, config, hostProxy, liveTun := old, "before", !test.oldTun, test.oldTun
			var events []string
			fail := test.fail
			step := func(name string) error {
				events = append(events, name)
				if fail == name {
					fail = ""
					return errors.New("fixture " + name)
				}
				return nil
			}
			ops := modeSwitchOps{
				reload:       func(ctx context.Context, b []byte, tun bool) error { liveTun = tun; return step("reload") },
				setProxy:     func() (*core.ProxySnapshot, error) { hostProxy = true; return baseline, step("set") },
				restoreProxy: func(*core.ProxySnapshot) error { hostProxy = false; return step("restore") },
				config:       func(b []byte) error { config = string(b); return step("config") },
				state:        func(st clientState) error { stored = st; return step("state") },
			}
			err := applyDesktopModes(context.Background(), old, []byte("before"), []byte("after"), test.newTun, ops)
			if test.fail != "" {
				if err == nil || liveTun != test.oldTun || hostProxy != !test.oldTun || config != "before" || !reflect.DeepEqual(old, stored) {
					t.Fatalf("incomplete rollback: err=%v tun=%v proxy=%v config=%s events=%v", err, liveTun, hostProxy, config, events)
				}
			} else {
				if err != nil || liveTun != test.newTun || hostProxy != !test.newTun || stored.TUN != test.newTun || config != "after" || stored.CorePID != old.CorePID || stored.StartedAt != old.StartedAt {
					t.Fatalf("bad commit: %v %+v %v", err, stored, events)
				}
				if test.oldTun == test.newTun && (strings.Contains(strings.Join(events, ","), "set") || strings.Contains(strings.Join(events, ","), "restore")) {
					t.Fatal("routing-only reload must not touch host proxy")
				}
				if test.oldTun == test.newTun && !reflect.DeepEqual(stored.ProxySnap, old.ProxySnap) {
					t.Fatal("snapshot lost on routing-only reload")
				}
			}
		})
	}
}

func TestDesktopModeRollbackFailureVisible(t *testing.T) {
	ops := modeSwitchOps{reload: func(context.Context, []byte, bool) error { return errors.New("reload failed") }}
	err := applyDesktopModes(context.Background(), clientState{}, nil, nil, true, ops)
	if err == nil || !strings.Contains(err.Error(), "回滚未完成") {
		t.Fatalf("rollback failure hidden: %v", err)
	}
}

// Optional real-binary parser check. -t only: no core listeners, proxy writes,
// registration or tunnel dials. Only the two public geodata files are copied.
func TestDesktopModeConfigsAccepted(t *testing.T) {
	bin, source := os.Getenv("WARP_TEST_MIHOMO"), os.Getenv("WARP_TEST_GEO_DIR")
	if bin == "" || source == "" {
		t.Skip("set WARP_TEST_MIHOMO and WARP_TEST_GEO_DIR for parser checks")
	}
	home := t.TempDir()
	t.Setenv("WARP_CLIENT_HOME", home)
	dir := filepath.Join(home, "core")
	if err := os.MkdirAll(dir, 0700); err != nil {
		t.Fatal(err)
	}
	for _, name := range core.GeoDataNames() {
		b, err := os.ReadFile(filepath.Join(source, name))
		if err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(filepath.Join(dir, name), b, 0600); err != nil {
			t.Fatal(err)
		}
	}
	for _, proto := range []string{protoWG, protoAWG, protoMASQUE, protoMASQUEH2, protoWWarp, protoMASQUEMASQUE} {
		t.Run(proto, func(t *testing.T) {
			probe, err := probeYAML(proto)
			if err != nil {
				t.Fatal(err)
			}
			nodes, _, ok := strings.Cut(probe, "rules:\n")
			if !ok {
				t.Fatal("missing probe nodes")
			}
			egress := "PROBE"
			if proto == protoWWarp || proto == protoMASQUEMASQUE {
				egress = "PROBE INNER"
			}
			before := []byte("# generated by xehn (xehn)\n" + nodes + "proxy-groups:\n  - name: WARP\n    type: select\n    proxies: [\"" + egress + "\"]\nrules:\n  - MATCH,WARP\n")
			for _, capture := range []string{captureProxy, captureTun} {
				for _, route := range []string{modeGlobal, modeBypass} {
					s := defaultSettings()
					s.Proto = proto
					s.CaptureMode = capture
					s.ProxyMode = route
					s.DNSCustom = "223.5.5.5,1.1.1.1"
					after, err := desktopModeConfig(before, s, clientState{Connected: true, MixedPort: 17891, APIPort: 19090})
					if err != nil {
						t.Fatal(err)
					}
					if err := core.TestConfig(bin, dir, after); err != nil {
						t.Fatalf("%s/%s: %v", capture, route, err)
					}
				}
			}
		})
	}
}
